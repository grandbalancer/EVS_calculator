def prepare_original():
    ORIG_DIR.mkdir(parents=True, exist_ok=True)
    if not ORIG.exists():
        shutil.copy2(TARGET, ORIG)


def fix(ws, addr, new, why):
    old = ws[addr].value
    ws[addr].value = new
    ws[addr].fill = CHANGED
    log.append((ws.title, addr, old, new, why))


def add_status_columns(ws, header_row, first_row, last_row, statuses):
    """statuses: {номер_строки: (статус, примечание)}"""
    c1 = ws.max_column + 1
    c2 = c1 + 1
    hdr_src = ws.cell(header_row, c1 - 1)
    data_src = ws.cell(first_row, c1 - 1)
    for col, title, width in ((c1, "Статус сверки", 18), (c2, "Примечание к сверке", 60)):
        h = ws.cell(header_row, col, title)
        h._style = copy(hdr_src._style)
        ws.column_dimensions[openpyxl.utils.get_column_letter(col)].width = width
    for r in range(first_row, last_row + 1):
        status, note = statuses.get(r, ("Не сверено", ""))
        s = ws.cell(r, c1, status)
        n = ws.cell(r, c2, note)
        s._style = copy(data_src._style)
        n._style = copy(data_src._style)
        s.fill = FILL[status]
        n.alignment = Alignment(wrap_text=True, vertical="top")
        s.alignment = Alignment(wrap_text=True, vertical="top")


def new_sheet(wb, title, heading, headers, rows, widths, like_ws, status_col=None):
    ws = wb.create_sheet(title)
    ws["A1"] = heading
    ws["A1"]._style = copy(like_ws["A1"]._style)
    for i, h in enumerate(headers, 1):
        c = ws.cell(3, i, h)
        c._style = copy(like_ws["A3"]._style)
    for r, row in enumerate(rows, 4):
        for i, v in enumerate(row, 1):
            c = ws.cell(r, i, v)
            c._style = copy(like_ws["A4"]._style)
            c.alignment = Alignment(wrap_text=True, vertical="top")
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    return ws


def read_manual(name):
    with open(MANUAL / f"{name}.csv", encoding="utf-8-sig", newline="") as f:
        return list(csv.reader(f, delimiter=";"))


